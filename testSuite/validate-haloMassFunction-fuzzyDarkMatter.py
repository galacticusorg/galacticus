#!/usr/bin/env python3
import os
import sys
import subprocess
import numpy as np
import h5py

# Test fuzzy dark matter halo mass function against Du et al. (2017) results.
# Yu Zhao (13-October-2026)

# Specify digitized FDM halo mass function from Du et al. (2017), Figure 3 (upper panel), z = 0.
du2017DataPath = "data/haloMassFunction/du2017haloMassFunction_z0.txt"

# Specify the Galacticus output file.
fileName = "outputs/haloMassFunctionDu2017_new.hdf5"

# Create output path.
try:
    os.mkdir("outputs")
except FileExistsError:
    pass

# Read the Du et al. (2017) mass function.
mass, massFunction = np.loadtxt(
                                du2017DataPath,
                                usecols=(0, 1),
                                unpack=True
                                )

# Convert from the units used in Du et al. (2017) to Galacticus units.
h             = 0.6781
mass         /= h
massFunction *= h**3

# Run Galacticus to generate the mass function.
status = subprocess.run("cd ..; ./Galacticus.exe testSuite/parameters/haloMassFunctionDu2017.xml",shell=True)
if status.returncode != 0:
    print("FAILED: Galacticus failed for 'fuzzyDarkMatterDu2017'")
    sys.exit(0)
if not os.path.exists(fileName):
    print("FAILED: Galacticus produced no output file for 'fuzzyDarkMatterDu2017'")
    sys.exit(0)

# Read the mass function generated by Galacticus.
with h5py.File(fileName, "r") as massFunctionFile:
    massGalacticus = massFunctionFile['Outputs/Output1/haloMass'][:]
    massFunctionGalacticus = massFunctionFile['Outputs/Output1/haloMassFunctionLnM'][:]

# Select positive Galacticus mass function values.
selection = (massGalacticus > 0.0) & (massFunctionGalacticus > 0.0)

massGalacticusValid = massGalacticus[selection]
massFunctionGalacticusValid = massFunctionGalacticus[selection]

# Sort by halo mass for interpolation.
order = np.argsort(massGalacticusValid)

massGalacticusValid = massGalacticusValid[order]
massFunctionGalacticusValid = massFunctionGalacticusValid[order]

# Restrict comparison to masses above the low-mass cutoff region.
# Du et al. (2017) report a cutoff mass of approximately 6e8 h^-1 Msun at z = 0.
# We compare the HMF at M >= 2e9 Msun to avoid the steep cutoff region.
massMinimumComparison = 2.0e9  # Msun

selection = (
    (mass >= massMinimumComparison) &
    (mass >= massGalacticusValid.min()) &
    (mass <= massGalacticusValid.max()) &
    (massFunction > 0.0)
)

massComparison = mass[selection]
massFunctionComparison = massFunction[selection]

if len(massComparison) == 0:
    print("FAILED: [fuzzyDarkMatterDu2017] no valid comparison points")
    sys.exit(0)

# Interpolate the Galacticus mass function to the Du et al. (2017) masses.
massFunctionGalacticusInterpolated = 10.0**np.interp(
    np.log10(massComparison),
    np.log10(massGalacticusValid),
    np.log10(massFunctionGalacticusValid)
)

# Compare mass functions.
differenceLogarithmic = np.abs(
    np.log10(massFunctionComparison) -
    np.log10(massFunctionGalacticusInterpolated)
)

differenceLogarithmicMaximum = np.max(differenceLogarithmic)

print(f"Maximum logarithmic difference: {differenceLogarithmicMaximum:.4f} dex")

if differenceLogarithmicMaximum > 1.5e-1:
    print("FAILED: [fuzzyDarkMatterDu2017] mass function differs")
    sys.exit(0)
else:
    print("success: [fuzzyDarkMatterDu2017] mass functions agree")

