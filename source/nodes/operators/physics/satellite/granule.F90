  subroutine satelliteGranuleNodeInitialize(self,node)
    !!{RST
    Initialize the stochastic granule state of a satellite. Reset the phase, store the integration time and core fluctuation
    frequency, and draw independent dimensionless Gaussian Fourier coefficients for the core and outer stochastic fields.
    !!}
    use :: Coordinates                        , only : coordinateSpherical         , assignment(=)
    use :: Dark_Matter_Profiles_Soliton_Status, only : enumerationSolitonStatusType, solitonStatusNfwOnly          , solitonStatusSolitonNFW, &
         &                                             solitonStatusSolitonOnly
    use :: Error                              , only : Error_Report
    use :: Galacticus_Nodes                   , only : nodeComponentBasic          , nodeComponentDarkMatterProfile, treeNode
    use :: Mass_Distributions                 , only : massDistributionClass       , kinematicsDistributionClass
    implicit none
    class            (nodeOperatorSatelliteGranule  ), intent(inout), target      :: self
    type             (treeNode                      ), intent(inout), target      :: node
    type             (treeNode                      ),                pointer     :: nodeHost
    class            (nodeComponentBasic            ),                pointer     :: basic                  , basicHost
    class            (nodeComponentDarkMatterProfile),                pointer     :: darkMatterProfileHost
    class            (massDistributionClass         )               , pointer     :: massDistributionHost_
    class            (kinematicsDistributionClass   )               , pointer     :: kinematicsHost_
    type             (coordinateSpherical           )                             :: coordinates
    type             (enumerationSolitonStatusType  )                             :: solitonStatus
    double precision                                 , dimension(:) , allocatable :: axnCore                , aynCore           , &
                     &                                                               aznCore                , axnOuter          , &
                     &                                                               aynOuter               , aznOuter
    double precision                                                              :: maxTime                , densityCore       , &
                     &                                                               frequencyCore          , alphaCoreComponent, &
                     &                                                               velocityDispersionJeans
    integer                                                                       :: i                      , stepNum

    ! Initialize current satellites and secondary progenitors that can become satellites after a merger; skip primary or
    ! parentless central nodes.
    if (.not. node%isSatellite() .and. (node%isPrimaryProgenitor() .or. .not. associated(node%parent))) return
    ! Find the top-level host node.
    if (node%isSatellite()) then
       nodeHost => node%parent
    else
       nodeHost => node%parent%firstChild
    end if    
    do while (associated(nodeHost%parent))
       nodeHost => nodeHost%parent
    end do
    ! Extract properties of the host node.
    basicHost => nodeHost %basic()
    maxTime   =  basicHost%time ()
    ! Reset to the immediate host.
    if (node%isSatellite()) then
       nodeHost => node%parent
    else
       nodeHost => node%parent%firstChild
    end if    
    ! Get the host mass distribution. Doing so first ensures that the soliton status of the host has been determined.
    massDistributionHost_ => self%darkMatterProfileDMO_%get(nodeHost)
    darkMatterProfileHost => nodeHost%darkMatterProfile()
    solitonStatus         =  enumerationSolitonStatusType(darkMatterProfileHost%integerRank0MetaPropertyGet(self%solitonStatusID))
    if      (solitonStatus == solitonStatusSolitonNFW .or. solitonStatus == solitonStatusSolitonOnly) then
       ! Core oscillation frequency; reference density 10⁹ M☉/kpc³ = 10¹⁸ M☉/Mpc³ (Dutta Chowdhury et al. 2021). The
       ! central density of the soliton is taken from the stored core density (which is the central density of the Schive et
       ! al. 2014 profile), the same quantity used to rescale the phase rate as the host evolves, so that the rescaling starts
       ! from exactly 1.
       densityCore   =+darkMatterProfileHost%floatRank0MetaPropertyGet(self%densityCoreID) ! M☉/Mpc³
       frequencyCore =+10.94d0*sqrt(densityCore/1.0d18)                                    ! Gyr⁻¹
    else if (solitonStatus == solitonStatusNfwOnly                                         ) then
       ! An NFW-only host has no soliton, so no core frequency exists (and the central density of the NFW profile is
       ! divergent). Instead use the outer granule frequency at the scale radius, which is close to the peak of the Jeans
       ! velocity dispersion of an NFW profile, and so to the highest outer granule frequency in the host. This frequency sets
       ! the number of Fourier modes, and is the reference for the (unscaled) phase rate of this host. The core term is zero
       ! for this host, so the frequency plays no role in its normalization.
       kinematicsHost_         => massDistributionHost_%kinematicsDistribution()
       coordinates             =  [darkMatterProfileHost%scale(),0.0d0,0.0d0]
       velocityDispersionJeans =  kinematicsHost_%velocityDispersion1D(coordinates,massDistributionHost_,massDistributionHost_) ! km/s
       frequencyCore           =  frequencyGranuleOuter(self,velocityDispersionJeans)                                           ! Gyr⁻¹
       !![
       <objectDestructor name="kinematicsHost_"/>
       !!]
    else
       frequencyCore           =  0.0d0
       call Error_Report('soliton status of host halo is uninitialized'//{introspection:location})
    end if
    !![
    <objectDestructor name="massDistributionHost_"/>
    !!]
    ! Truncate the Paley-Wiener Fourier series at m = 4*f_core*t_max.
    ! The factor 4 ensures empirical convergence of acceleration statistics.
    stepNum  = ceiling(4.0d0*frequencyCore*maxTime)
    ! Adjust the integration time to match the integer number of modes.
    maxTime = stepNum/(4.0d0*frequencyCore)
    ! Store properties of the Paley-Wiener series.    
    basic => node%basic()
    call basic%floatRank0MetaPropertySet(self%tauID          ,0.0d0        )
    call basic%floatRank0MetaPropertySet(self%frequencyCoreID,frequencyCore)
    call basic%floatRank0MetaPropertySet(self%maxTimeID      ,maxTime      )
    call basic%integerRank0MetaPropertySet(self%stepNumID    ,stepNum      )
    ! Record the host, and its soliton status, for which this realization is drawn, so that a new realization can be drawn if
    ! either changes.
    call basic%integerRank0MetaPropertySet    (self%statusHostID  ,solitonStatus%ID                           )
    call basic%longIntegerRank0MetaPropertySet(self%identityHostID,satelliteGranuleHaloIdentity(self,nodeHost))
    ! The core acceleration is isotropic and a_eff^core denotes its total three-dimensional RMS amplitude, so each Cartesian
    ! component carries a factor 1/√3.
    alphaCoreComponent=self%alphaCore/sqrt(3.0d0)
    allocate(axnCore (0:stepNum))
    allocate(aynCore (0:stepNum))
    allocate(aznCore (0:stepNum))
    allocate(axnOuter(0:stepNum))
    allocate(aynOuter(0:stepNum))
    allocate(aznOuter(0:stepNum))
    ! Draw independent dimensionless Gaussian Fourier coefficients for each Cartesian component of the core and outer stochastic
    ! fields.
    do i = 0, stepNum
       axnCore (i)=     alphaCoreComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       aynCore (i)=     alphaCoreComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       aznCore (i)=     alphaCoreComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       axnOuter(i)=self%alphaOuter        *node%hostTree%randomNumberGenerator_%standardNormalSample()
       aynOuter(i)=self%alphaOuter        *node%hostTree%randomNumberGenerator_%standardNormalSample()
       aznOuter(i)=self%alphaOuter        *node%hostTree%randomNumberGenerator_%standardNormalSample()
    end do
    ! Store the coefficients.
    call basic%floatRank1MetaPropertySet(self%axnCoreID ,axnCore )
    call basic%floatRank1MetaPropertySet(self%aynCoreID ,aynCore )
    call basic%floatRank1MetaPropertySet(self%aznCoreID ,aznCore )
    call basic%floatRank1MetaPropertySet(self%axnOuterID,axnOuter)
    call basic%floatRank1MetaPropertySet(self%aynOuterID,aynOuter)
    call basic%floatRank1MetaPropertySet(self%aznOuterID,aznOuter)
    return
  end subroutine satelliteGranuleNodeInitialize

  function granuleAcceleration(self,node)
    !!{RST
    Compute the stochastic acceleration generated by fuzzy-dark-matter granules in the host halo. Core and outer stochastic fields
    are evaluated separately, and the outer contribution includes the velocity-dependent anisotropy.  Units: km/s/Gyr (same as
    other dynamical friction acceleration models).
    !!}
    use :: Galacticus_Nodes                   , only : nodeComponentBasic            , nodeComponentSatellite     , nodeComponentDarkMatterProfile, treeNode
    use :: Dark_Matter_Profiles_Soliton_Status, only : enumerationSolitonStatusType  , solitonStatusNfwOnly       , solitonStatusSolitonOnly
    use :: Coordinates                        , only : coordinateSpherical           , assignment(=)
    use :: Mass_Distributions                 , only : massDistributionClass         , kinematicsDistributionClass
    use :: Numerical_Constants_Astronomical   , only : gravitationalConstant_internal, MpcPerKmPerSToGyr
    use :: Vectors                            , only : Vector_Magnitude
    implicit none
    double precision                                               , dimension(3) :: granuleAcceleration
    class           (nodeOperatorSatelliteGranule  ), intent(inout), target       :: self
    type            (treeNode                      ), intent(inout)               :: node
    type            (treeNode                      )               , pointer      :: nodeHost
    class           (nodeComponentBasic            )               , pointer      :: basic
    class           (nodeComponentSatellite        )               , pointer      :: satellite
    class           (massDistributionClass         )               , pointer      :: massDistributionHost_
    class           (kinematicsDistributionClass   )               , pointer      :: kinematicsHost_
    class           (nodeComponentDarkMatterProfile)               , pointer      :: darkMatterProfileHost
    type            (coordinateSpherical           )                              :: coordinates                     , coordinatesSoliton
    type            (enumerationSolitonStatusType  )                              :: solitonStatus
    double precision                                                              :: velocityDispersionJeans         , velocityDispersionJeansSoliton
    double precision                                                              :: densityLocal                    , densitySoliton                , &
            &                                                                        massCore                        , radiusSoliton                 , &
            &                                                                        radiusCore
    double precision                                                              :: amplCore                        , amplOuter
    double precision                                                              :: frequencyCore                   , frequencyOuter
    double precision                                                              :: radius                          , velocityNorm                  , &
            &                                                                        tau                             , maxTime
    double precision                                                              :: velocityDispersionGranule       , finiteSizeFactor
    double precision                                                              :: Atotal                          , factorPerpendicular           , &
            &                                                                        factorParallel
    double precision                                               , dimension(3) :: positionSatellite               , velocitySatellite
    double precision                                ,  dimension(:), allocatable  :: arrayN
    double precision                                ,  dimension(:), allocatable  :: axnCore                         , aynCore                       , &
            &                                                                        aznCore                         , axnOuter                      , &
            &                                                                        aynOuter                        , aznOuter
    double precision                                                              :: axCore                          , ayCore                        , &
            &                                                                        azCore                          , axOuter                       , &
            &                                                                        ayOuter                         , azOuter
    double precision                                               , dimension(3) :: aRawCore                        , aRawOuter                     , &
            &                                                                        aRawPar                         , aRawPerp                      , &
            &                                                                        velocityDirection
    double precision                                               , dimension(3) :: aPar                            , aPerp
    double precision                                               , parameter    :: fractionSmall            =1.0d-2
    integer                                                                       :: stepNum
    !$GLC attributes initialized :: axnCore, aynCore, aznCore, axnOuter, aynOuter, aznOuter

    ! Non-satellites experience no granule acceleration.
    if (.not.node%isSatellite()) then
      granuleAcceleration=[0.0d0, 0.0d0, 0.0d0]
      return
    end if
    ! Extract satellite and host properties.
    satellite             => node            %satellite        (                 )
    basic                 => node            %basic            (                 )
    positionSatellite     =  satellite       %position         (                 )
    radius                =  Vector_Magnitude                  (positionSatellite)
    velocitySatellite     =  satellite       %velocity         (                 )
    velocityNorm          =  Vector_Magnitude                  (velocitySatellite)
    nodeHost              => node            %parent
    darkMatterProfileHost => nodeHost        %darkMatterProfile(                 )
    ! The granules belong to the host FDM halo, so both the density and the Jeans velocity dispersion must be evaluated from the
    ! host profile.
    massDistributionHost_ => self                 %darkMatterProfileDMO_%get                   (nodeHost)
    kinematicsHost_       => massDistributionHost_                      %kinematicsDistribution(        )
    ! Extract the Fourier coefficients for the accelerations.
    axnCore =basic%floatRank1MetaPropertyGet(self%axnCoreID )
    aynCore =basic%floatRank1MetaPropertyGet(self%aynCoreID )
    aznCore =basic%floatRank1MetaPropertyGet(self%aznCoreID )
    axnOuter=basic%floatRank1MetaPropertyGet(self%axnOuterID)
    aynOuter=basic%floatRank1MetaPropertyGet(self%aynOuterID)
    aznOuter=basic%floatRank1MetaPropertyGet(self%aznOuterID)
    ! Extract other properties of the Fourier series.
    maxTime      =basic%floatRank0MetaPropertyGet  (self%maxTimeID      )
    frequencyCore=basic%floatRank0MetaPropertyGet  (self%frequencyCoreID)
    tau          =basic%floatRank0MetaPropertyGet  (self%tauID          )
    stepNum      =basic%integerRank0MetaPropertyGet(self%stepNumID      )
    arrayN       =arrayCos(tau,stepNum)
    solitonStatus=enumerationSolitonStatusType(darkMatterProfileHost%integerRank0MetaPropertyGet(self%solitonStatusID))
    ! Compute acceleration amplitudes.
    if (solitonStatus == solitonStatusNfwOnly) then
        ! NFW-only: radiusCore and radiusSoliton are sentinel values (-1), so use only the density and Jeans velocity dispersion
        ! at the satellite.
        coordinates              = [radius,0.0d0,0.0d0]
        velocityDispersionJeans  =+kinematicsHost_      %velocityDispersion1D(coordinates,massDistributionHost_,massDistributionHost_) ! km/s
        densityLocal             =+massDistributionHost_%density             (coordinates                                            ) ! M☉/Mpc³
        amplCore                 = 0.0d0
        amplOuter                = amplitudeOuter       (self,velocityDispersionJeans,densityLocal)
        frequencyOuter           = frequencyGranuleOuter(self,velocityDispersionJeans             )
        velocityDispersionGranule= velocityDispersionJeans
    else if (solitonStatus == solitonStatusSolitonOnly) then
        ! Soliton-only: retain the core fluctuation and omit the outer granule term.
        massCore  =darkMatterProfileHost%floatRank0MetaPropertyGet(self%massCoreID  )
        radiusCore=darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusCoreID)
        if (radius <= radiusCore) then
           amplCore=+gravitationalConstant_internal &
                &   *massCore                       &
                &   /radiusCore**2                  &
                &   /MpcPerKmPerSToGyr
        else
            amplCore=+0.0d0
        end if
        amplOuter   =+0.0d0
     else
        ! General (soliton+NFW) case.
        massCore     =darkMatterProfileHost%floatRank0MetaPropertyGet(self%massCoreID     )
        radiusCore   =darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusCoreID   )
        radiusSoliton=darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusSolitonID)
        ! Impose a small radial floor relative to the soliton core radius to avoid evaluating the density and Jeans velocity dispersion at r=0.
        radius            =max(radius,fractionSmall*radiusCore)
        coordinates       =[radius       ,0.0d0,0.0d0]
        coordinatesSoliton=[radiusSoliton,0.0d0,0.0d0]
        ! Compute the acceleration amplitudes.
        velocityDispersionJeans        =+kinematicsHost_      %velocityDispersion1D(coordinates       ,massDistributionHost_,massDistributionHost_) ! km/s
        velocityDispersionJeansSoliton =+kinematicsHost_      %velocityDispersion1D(coordinatesSoliton,massDistributionHost_,massDistributionHost_) ! km/s
        densityLocal                   =+massDistributionHost_%density             (coordinates                                                   ) ! M☉/Mpc³
        densitySoliton                 =+massDistributionHost_%density             (coordinatesSoliton                                            ) ! M☉/Mpc³
        if (radius<=radiusCore) then
           amplCore                 =+gravitationalConstant_internal &                                         ! km/s/Gyr
                &                    *massCore                       &
                &                    /radiusCore**2                  &
                &                    /MpcPerKmPerSToGyr
           amplOuter                =amplitudeOuter       (self,velocityDispersionJeansSoliton,densitySoliton) ! km/s/Gyr
           frequencyOuter           =frequencyGranuleOuter(self,velocityDispersionJeansSoliton               ) ! Gyr⁻¹
           velocityDispersionGranule=velocityDispersionJeansSoliton
        else if (radius<=radiusSoliton) then
            amplCore                 =0.0d0
            amplOuter                =amplitudeOuter(self,velocityDispersionJeansSoliton,densitySoliton)
            frequencyOuter           =frequencyGranuleOuter(self,velocityDispersionJeansSoliton)
            velocityDispersionGranule=velocityDispersionJeansSoliton
        else
            amplCore                 =0.0d0
            amplOuter                =amplitudeOuter       (self,velocityDispersionJeans,densityLocal)
            frequencyOuter           =frequencyGranuleOuter(self,velocityDispersionJeans             )
            velocityDispersionGranule=velocityDispersionJeans
        end if
    end if
    ! Keep the tested point-mass path unchanged. For a finite-size satellite, multiply only the outer stochastic amplitude by the
    ! relative suppression inferred from the finite-size calibration. The Fourier process and its correlation frequency are
    ! unchanged.
    if (self%applyFiniteSize .and. solitonStatus /= solitonStatusSolitonOnly) then
        finiteSizeFactor=finiteSizeAmplitudeFactor(self,node,velocityDispersionGranule)
        amplOuter       =finiteSizeFactor*amplOuter
    end if
    !![
    <objectDestructor name="kinematicsHost_"      />
    <objectDestructor name="massDistributionHost_"/>
    !!]

    if (solitonStatus == solitonStatusNfwOnly) then
        ! An NFW-only halo has no core fluctuation.
        aRawCore=[0.0d0,0.0d0,0.0d0]
    else
        ! The Fourier coefficients and arrayN are dimensionless. Since frequency
        ! is in Gyr⁻¹ and maxTime is in Gyr, √(frequency*maxTime) is also
        ! dimensionless. Therefore aRawCore and aRawOuter are dimensionless.
        axCore  =dot_product(axnCore,arrayN)/sqrt(frequencyCore*maxTime)
        ayCore  =dot_product(aynCore,arrayN)/sqrt(frequencyCore*maxTime)
        azCore  =dot_product(aznCore,arrayN)/sqrt(frequencyCore*maxTime)
        aRawCore=[axCore,ayCore,azCore]
    end if
    ! For a soliton-only profile the acceleration is due to the core only. Scale the raw acceleration by the amplitude and return
    ! it.
    if (solitonStatus == solitonStatusSolitonOnly) then
        granuleAcceleration = amplCore*aRawCore
        return
    end if
    ! For profiles with an NFW component include the acceleration from the granules in the outer halo.
    axOuter  =dot_product(axnOuter,arrayN)/sqrt(frequencyOuter*maxTime)
    ayOuter  =dot_product(aynOuter,arrayN)/sqrt(frequencyOuter*maxTime)
    azOuter  =dot_product(aznOuter,arrayN)/sqrt(frequencyOuter*maxTime)
    aRawOuter=[axOuter,ayOuter,azOuter]
    ! Compute a unit vector in the direction of the satellite velocity.
    if (velocityNorm > 0.0d0) then
       velocityDirection=+velocitySatellite &
            &            /velocityNorm
    else
        velocityDirection=[0.0d0, 0.0d0, 0.0d0]
    end if
    ! velocityNorm and velocityDispersionJeans are both in km/s, so Atotal, factorPerpendicular, factorParallel, aPar, and aPerp
    ! are dimensionless.
    Atotal             =sqrt(1.0d0+      (velocityNorm/velocityDispersionJeans)**2)
    factorPerpendicular=sqrt(1.0d0+0.5d0*(velocityNorm/velocityDispersionJeans)**2)
    factorParallel     =1.0d0/(3.0d0/Atotal-2.0d0/factorPerpendicular)
    ! The velocity-dependent factor is applied only to a_raw_outer.
    ! The acceleration from the core is set to 0 at d > r_c.
    aRawPar =dot_product(aRawOuter,velocityDirection)*velocityDirection
    aRawPerp=aRawOuter-aRawPar
    aPar    =aRawPar /sqrt(factorParallel     )
    aPerp   =aRawPerp/sqrt(factorPerpendicular)
    ! amplCore and amplOuter are in km/s/Gyr, while all stochastic and anisotropy factors are dimensionless. The returned
    ! acceleration is therefore in km/s/Gyr, as required by satellite%velocityRate().
    granuleAcceleration=+amplCore *  aRawCore &
         &              +amplOuter*(          &
         &                          +aPar     &
         &                          +aPerp    &
         &                         )
    return
  end function granuleAcceleration

  function arrayCos(tau, m) result(arr)
    !!{RST
    Return the dimensionless Fourier basis. Both ``tau`` and ``arr`` are dimensionless; ``m`` is the number of non-zero Fourier
    modes. The first element is 1/√2, followed by cos(nτ/2) for n = 1, 2, ..., m.
    !!}
    implicit none
    integer         , intent(in)                :: m
    double precision, intent(in)                :: tau
    double precision, allocatable, dimension(:) :: arr
    integer                                     :: n

    allocate(arr(0:m))
    arr(0)=1.0d0/sqrt(2.0d0)
    do n=1,m
        arr(n)=cos(dble(n)*tau/2.0d0)
    end do
    return
  end function arrayCos

  function amplitudeOuter(self,velocityDispersionJeans,densityBackground)
    !!{RST
    Compute the outer-halo effective granule acceleration amplitude.
    !!}
    use :: Numerical_Constants_Astronomical, only : gravitationalConstant_internal, megaParsec, MpcPerKmPerSToGyr
    use :: Numerical_Constants_Prefixes    , only : kilo
    use :: Numerical_Constants_Physical    , only : plancksConstant
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout), target :: self
    double precision                              , intent(in   )         :: velocityDispersionJeans, densityBackground
    double precision                                                      :: amplitudeOuter         , LambdaDB         , &
            &                                                                deff                   , meff                                  
    
    ! plancksConstant [J s] / (massParticleSI [kg] * velocity [m/s])
    ! gives LambdaDB in metres; division by megaParsec converts it to Mpc.
    LambdaDB=plancksConstant/self%massParticleSI/(velocityDispersionJeans*kilo)/megaParsec ! Mpc
    deff    =0.35d0*LambdaDB                                                               ! Mpc
    meff    =densityBackground*(0.282d0*LambdaDB)**3                                       ! M☉
    ! gravitationalConstant_internal*meff/deff² has units (km/s)²/Mpc. Convert to the velocity evolution unit km/s/Gyr.
    amplitudeOuter=+gravitationalConstant_internal & ! km/s/Gyr
         &         *meff                           &
         &         /deff**2                        &
         &         /MpcPerKmPerSToGyr
    return
  end function amplitudeOuter

  double precision function frequencyGranuleOuter(self,velocityDispersionJeans)
    !!{RST
    Return the characteristic frequency (in Gyr\ :math:`^{-1}`) of outer-halo granule fluctuations, :math:`f = m
    \sigma^2/(0.35\sqrt{2}h)`, for a host with Jeans velocity dispersion ``velocityDispersionJeans`` (in km/s).
    !!}
    use :: Numerical_Constants_Astronomical, only : gigaYear
    use :: Numerical_Constants_Prefixes    , only : kilo
    use :: Numerical_Constants_Physical    , only : plancksConstant
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout) :: self
    double precision                              , intent(in   ) :: velocityDispersionJeans

    frequencyGranuleOuter=+self%massParticleSI               &
         &                *(velocityDispersionJeans*kilo)**2 &
         &                /0.35d0                            &
         &                /sqrt(2.0d0)                       &
         &                /plancksConstant                   &
         &                *gigaYear
    return
  end function frequencyGranuleOuter

  double precision function finiteSizeAmplitudeFactor(self,node,velocityDispersionJeans)
    !!{RST
    Return the finite-size suppression of the outer granule acceleration.  The satellite half-mass radius is evaluated from its
    current bound dark matter mass. The effective granule size is :math:`d_\mathrm{eff}=0.35\lambda_\mathrm{dB}`. Satellites with
    :math:`r_\mathrm{half}/d_\mathrm{eff}\leq0.40` retain the point-mass amplitude. Above this transition, the acceleration
    amplitude is suppressed as :math:`(r_\mathrm{half}/0.40d_\mathrm{eff})^{-0.229}`. Because a velocity-diffusion coefficient is
    proportional to acceleration variance, the corresponding diffusion coefficient is multiplied by the square of this factor.
    !!}
    use :: Galacticus_Nodes                , only : nodeComponentSatellite, treeNode
    use :: Galactic_Structure_Options      , only : componentTypeAll      , massTypeDark, radiusLarge
    use :: Mass_Distributions              , only : massDistributionClass
    use :: Numerical_Constants_Astronomical, only : megaParsec
    use :: Numerical_Constants_Prefixes    , only : kilo
    use :: Numerical_Constants_Physical    , only : plancksConstant
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout), target   :: self
    type            (treeNode                    ), intent(inout), target   :: node
    double precision                              , intent(in   )           :: velocityDispersionJeans
    class           (nodeComponentSatellite      )               , pointer  :: satellite
    class           (massDistributionClass       )               , pointer  :: massDistributionSatellite_
    double precision                                                        :: deff                             , lambdaDB             , &
            &                                                                  massBound                        , massMaximum          , &
            &                                                                  massHalf                         , massAtOrigin         , &
            &                                                                  radiusHalf                       , sizeRatio
    ! The transition ratio and suppression exponent are determined from numerical calibration of the finite-size correction.
    double precision                                            , parameter :: sizeRatioTransition       =0.40d0, exponentSize=-0.229d0

    ! Extract the satellite mass distribution.
    satellite                 => node% satellite      (                                                    )
    massDistributionSatellite_=> node%massDistribution(componentType=componentTypeAll,massType=massTypeDark)
    ! Limit the requested bound mass to the finite mass represented by the satellite profile, then locate the radius containing
    ! half of that mass.
    massMaximum =massDistributionSatellite_%massEnclosedBySphere(radius=radiusLarge)
    massBound   =max(0.0d0,min(satellite%boundMass(),massMaximum))
    massHalf    =0.5d0*massBound
    massAtOrigin=massDistributionSatellite_%massEnclosedBySphere(radius=0.0d0)
    if (massHalf > massAtOrigin) then
       radiusHalf=massDistributionSatellite_%radiusEnclosingMass(mass=massHalf)
    else
       radiusHalf=0.0d0
    end if
    !![
    <objectDestructor name="massDistributionSatellite_"/>
    !!]
    ! Compute the ratio of the satellite size to that of granules.
    lambdaDB =plancksConstant/self%massParticleSI/(velocityDispersionJeans*kilo)/megaParsec ! Mpc
    deff     =0.35d0*lambdaDB                                                               ! Mpc
    sizeRatio=radiusHalf/deff
    ! Compute the finite size amplitude factor.
    if (sizeRatio <= sizeRatioTransition) then
       finiteSizeAmplitudeFactor=1.0d0
    else
       finiteSizeAmplitudeFactor=(                     &
            &                     +sizeRatio           &
            &                     /sizeRatioTransition &
            &                    )**exponentSize
    end if
    return
  end function finiteSizeAmplitudeFactor
