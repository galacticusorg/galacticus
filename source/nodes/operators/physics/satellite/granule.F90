  !![
  <nodeOperator name="nodeOperatorSatelliteGranule" docformat="rst">
   <description>
   A node operator class that applies the stochastic gravitational acceleration generated by fuzzy-dark-matter granules to an
   orbiting satellite, following the model of :cite:`zhao_granule_2025`.

   The stochastic acceleration is the sum of two statistically independent Gaussian random fields: one describing fluctuations
   of the solitonic core and one describing granules in the outer halo. :cite:`zhao_granule_2025` represent each Cartesian
   component of each field as a single truncated Paley--Wiener Fourier series spanning the whole time, :math:`t_\mathrm{max}`,
   over which the satellite is followed,

   .. math::

      a_i(t) =
      \frac{a_\mathrm{eff}}{\sqrt{f_\mathrm{granule}t_\mathrm{max}}}
      \left[
      \frac{A_{i,0}}{\sqrt{2}}+
      \sum_{n=1}^{m}A_{i,n}\cos\left(\frac{n\pi t}{t_\mathrm{max}}\right)
      \right],
      \quad
      m = 4 f_\mathrm{core}t_\mathrm{max},

   where the :math:`A_{i,n}` are independent Gaussian random variables with zero mean and standard deviation :math:`\alpha`,
   :math:`f_\mathrm{granule}` is the characteristic frequency of the fluctuations (the core or outer granule frequency), and the
   core oscillation frequency is

   .. math::

      f_\mathrm{core}
      =
      10.94\,\mathrm{Gyr}^{-1}
      \left(
      \frac{\rho_\mathrm{core}}
           {10^9\,M_\odot\,\mathrm{kpc}^{-3}}
      \right)^{1/2}.

   Such a series has :math:`m+1` coefficients per component, and for dense solitons followed over cosmological times
   :math:`m` reaches :math:`10^4`--:math:`10^6`, too many to store for every satellite or to sum at every timestep. This class
   instead builds a statistically equivalent field from short, overlapping series, whose coefficients are regenerated when
   needed rather than stored.

   **Construction.** A dimensionless phase, :math:`\phi`, counts cycles of the fluctuations, advancing at
   :math:`\mathrm{d}\phi/\mathrm{d}t = f_\mathrm{core}`, evaluated for the current state of the host, so that the fluctuation
   timescale follows changes in the host core density. Segment :math:`k` (for every integer :math:`k`) spans :math:`N` cycles,
   :math:`kN/2 \le \phi \le kN/2+N`, where :math:`N=` ``[countCyclesPerSegment]``, so that successive segments overlap by half
   their length. Within segment :math:`k`, at position :math:`s=(\phi-kN/2)/N`, the field is an independent series of the above
   form, with :math:`t_\mathrm{max}` replaced by the duration of the segment, :math:`T=N/f_\mathrm{core}`:

   .. math::

      X_{i,k}(s) =
      \frac{1}{\sqrt{f_\mathrm{granule}T}}
      \left[
      \frac{A_{i,k,0}}{\sqrt{2}}+
      \sum_{n=1}^{4N}A_{i,k,n}\cos(n\pi s)
      \right].

   Every phase lies within two segments, :math:`k` at position :math:`s \in [0,1/2)` and :math:`k-1` at position :math:`s+1/2`, and the
   two series are combined with weights that vanish at the ends of each segment:

   .. math::

      a_i = a_\mathrm{eff}\left[ \sin(\pi s)\, X_{i,k}(s) + \cos(\pi s)\, X_{i,k-1}(s+1/2) \right].

   The coefficients :math:`A_{i,k,n}` are drawn from a counter-based random number generator
   (:galacticus-class:`randomNumberGeneratorPhilox`), keyed by a seed drawn for each realization, with a counter set by the
   segment and the component. They are therefore a fixed function of :math:`(k,i,n)`, and the same values are regenerated
   whenever a segment is evaluated. Only the seed and the phase are stored for each satellite, and the work per evaluation,
   :math:`\propto N`, does not depend on :math:`f_\mathrm{core}` or :math:`t_\mathrm{max}`.

   **Equivalence to the single series.** Both constructions are zero-mean Gaussian processes, which are fully described by
   their covariance, so they are statistically equivalent if their covariances agree. Expanding the product of cosines, the
   covariance of the single series is

   .. math::

      \langle a_i(t) a_i(t^\prime) \rangle
      =
      \frac{\alpha^2 a_\mathrm{eff}^2}{2 f_\mathrm{granule} t_\mathrm{max}}
      \left[
      1
      + \sum_{n=1}^{m} \cos\left(\frac{n\pi (t-t^\prime)}{t_\mathrm{max}}\right)
      + \sum_{n=1}^{m} \cos\left(\frac{n\pi (t+t^\prime)}{t_\mathrm{max}}\right)
      \right].

   The first sum depends only on the lag, :math:`\Delta=t-t^\prime`. It is a sum over frequencies :math:`n/2t_\mathrm{max}` up to
   :math:`2f_\mathrm{core}`, which for :math:`t_\mathrm{max} \gg 1/f_\mathrm{core}` approaches the integral

   .. math::

      \langle a_i(t) a_i(t+\Delta) \rangle
      \approx
      \frac{\alpha^2 a_\mathrm{eff}^2}{f_\mathrm{granule}} \int_0^{2f_\mathrm{core}} \cos(2\pi\nu\Delta)\, \mathrm{d}\nu
      =
      \frac{2 f_\mathrm{core}}{f_\mathrm{granule}} \alpha^2 a_\mathrm{eff}^2 \, \mathrm{sinc}(4 f_\mathrm{core} \Delta),

   with :math:`\mathrm{sinc}(x)=\sin(\pi x)/\pi x`, independent of :math:`t_\mathrm{max}`. This is band-limited white noise,
   with a one-sided power spectrum :math:`\alpha^2 a_\mathrm{eff}^2/f_\mathrm{granule}` for frequencies below
   :math:`2f_\mathrm{core}`, and a correlation time of about :math:`1/4f_\mathrm{core}`. The normalization
   :math:`1/\sqrt{f_\mathrm{granule} t_\mathrm{max}}` is what makes the result independent of :math:`t_\mathrm{max}`. The
   second sum depends on :math:`t+t^\prime`, and is significant only within about :math:`1/f_\mathrm{core}` of the start and
   end of the series, where all modes are in phase. There it doubles the variance.

   Each segment is the same construction over the shorter time :math:`T`, so it has the same stationary covariance, provided
   that :math:`T` greatly exceeds the correlation time. For :math:`N=8` it is 32 correlation times. Because the segments are
   independent, the covariance of the combined field is that of a single segment multiplied by
   :math:`\sum_k w_k(t)w_k(t^\prime)`, where :math:`w_k` is the weight of segment :math:`k`. Since :math:`\sin^2(\pi
   s)+\cos^2(\pi s)=1`, this factor is exactly 1 at zero lag. For small lags it is
   :math:`1-\mathcal{O}[(\Delta/T)^2]`: it lies between :math:`\cos(\pi\Delta/T)` and 1, depending on the position within the
   segments, and so differs from 1 by less than :math:`1-\cos(\pi/4N)` (0.5% for :math:`N=8`) over a correlation time. In
   frequency this smooths the power spectrum over a width of about :math:`f_\mathrm{core}/2N`, which leaves the flat spectrum
   below :math:`2f_\mathrm{core}` unchanged and only softens its cutoff. For :math:`N=8` the spectrum is flat to 0.01% up
   to :math:`1.5f_\mathrm{core}`, is 0.7% below the flat value at :math:`1.9f_\mathrm{core}`, and falls to 70% of it at
   :math:`2f_\mathrm{core}`. The power at zero frequency, which sets the long-term integrated kick, is exactly that of the
   single series. The softened cutoff spreads a little power just above :math:`2f_\mathrm{core}`, so that, averaged over a
   segment, the variance is larger by a factor :math:`1+1/8N` (1.6% for :math:`N=8`). The orbital frequencies of satellites
   set the rate of orbital heating. Outside of the soliton they lie below :math:`f_\mathrm{core}`, in the flat part of the
   spectrum, so the heating rate is the same, and the calibration of :math:`\alpha` by :cite:`zhao_granule_2025` applies
   unchanged. Within the soliton they approach the cutoff: the orbital frequency, :math:`\sqrt{G\bar{\rho}/3\pi}` for mean
   enclosed density :math:`\bar{\rho}`, is :math:`1.6f_\mathrm{core}` at the core radius, :math:`1.9f_\mathrm{core}` at half
   of it, and :math:`2f_\mathrm{core}` at the center. Just inside the cutoff the single series is still flat while the
   segmented spectrum has begun to fall (the single series cuts off sharply, the segmented one over a width of about
   :math:`f_\mathrm{core}/2N`), so satellites orbiting at about :math:`0.15`--:math:`0.25` of the core radius experience
   heating lower than for the single series, by up to about 25% for :math:`N=8`. At the center the orbital frequency reaches
   :math:`2f_\mathrm{core}`, the edge of the band of the single series too, where both constructions receive only part of the
   flat-spectrum power, so the difference there is small. Larger :math:`N` sharpens the cutoff, and so confines this
   difference to smaller radii. Since the weights vanish at the ends of each segment, the endpoint terms of the segments do
   not contribute, so the field has no burst of doubled variance at the start of a realization. Individual realizations of
   course differ from those of a single series.

   With the phase advancing at the current core frequency, the duration of a segment is :math:`T=N/f_\mathrm{core}` for the
   current state of the host. The normalization :math:`1/\sqrt{f_\mathrm{granule}T}` is therefore :math:`1/\sqrt{N}` for the
   core field, and :math:`\sqrt{f_\mathrm{core}/N f_\mathrm{outer}}` for the outer field, so the power spectrum remains
   :math:`\alpha^2 a_\mathrm{eff}^2/f_\mathrm{granule}` as the host evolves.

   A new realization (a new seed, with the phase reset to zero) is drawn if the satellite moves to a different host halo (for
   example because its host merges, or through sub-subhalo promotion), or if its host changes soliton status (for example to
   soliton-only after tidal stripping), so the fluctuations are not correlated across such a change. Promotion of the host to
   its descendant in the merger tree does not change the host halo, so does not cause a new realization to be drawn.

   Within the solitonic core, the effective three-dimensional core acceleration is

   .. math::

      a_\mathrm{eff}^\mathrm{core}
      =
      \frac{G M_\mathrm{core}}{r_\mathrm{core}^2},

   and is applied only for :math:`r\leq r_\mathrm{core}`. Its Cartesian coefficients have standard deviation
   :math:`[\alpha_\mathrm{core}]/\sqrt{3}`, since :math:`a_\mathrm{eff}^\mathrm{core}` denotes the total isotropic RMS amplitude.

   The outer-halo contribution is estimated by treating granules as effective quasiparticles, with

   .. math::

      a_\mathrm{eff}^\mathrm{outer}
      =
      \frac{Gm_\mathrm{eff}}{d_\mathrm{eff}^2}.

   Its amplitude and frequency are evaluated using the density and Jeans velocity dispersion of the host halo. Inside the
   soliton they are fixed to their values at the soliton boundary; outside the soliton they are evaluated at the satellite
   position. The components parallel and perpendicular to the satellite velocity are rescaled separately to account for the
   velocity-dependent anisotropy of the granule perturbations. This rescaling is applied only to the outer contribution.

   For a soliton--NFW host, both the core and outer contributions are included. For a soliton-only host, only the core
   contribution is retained. For an NFW-only host, only the outer contribution is used, so the divergent central density of the
   NFW profile is never evaluated. Such a host has no core frequency, so in the phase rate and the segment duration
   :math:`f_\mathrm{core}` is replaced by the outer granule frequency evaluated at the scale radius of the host (close to the peak
   of its Jeans velocity dispersion) when the realization is drawn.

   If ``[applyFiniteSize]`` is false, the satellite is treated as a point mass. If it is true, the outer stochastic amplitude is
   suppressed according to the satellite half-mass radius relative to the effective granule size, following the finite-size
   calibration of :cite:`zhao_granule_2025`. The core contribution and fluctuation frequencies are unchanged by this
   correction.

   This operator requires a fuzzy-dark-matter particle model, a host dark-matter profile providing the soliton properties and
   Jeans velocity dispersion, and a satellite component which evolves the satellite position and velocity, such as the
   ``orbiting`` component.
   </description>
  </nodeOperator>
