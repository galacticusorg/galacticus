  subroutine satelliteGranuleNodeInitialize(self,node)
    !!{RST
    Initialize the stochastic granule state of a satellite. Reset the phase, store the integration time and core fluctuation
    frequency, and draw independent dimensionless Gaussian Fourier coefficients for the core and outer stochastic fields.
    !!}
    use :: Coordinates                        , only : coordinateSpherical         , assignment(=)
    use :: Dark_Matter_Profiles_Soliton_Status, only : enumerationSolitonStatusType, solitonStatusNfwOnly          , solitonStatusSolitonNFW, &
         &                                             solitonStatusSolitonOnly
    use :: Error                              , only : Error_Report
    use :: Galacticus_Nodes                   , only : nodeComponentBasic          , nodeComponentDarkMatterProfile, treeNode
    use :: Mass_Distributions                 , only : massDistributionClass       , kinematicsDistributionClass
    implicit none
    class            (nodeOperatorSatelliteGranule  ), intent(inout), target      :: self
    type             (treeNode                      ), intent(inout), target      :: node
    type             (treeNode                      ),                pointer     :: nodeHost
    class            (nodeComponentBasic            ),                pointer     :: basic                  , basicHost
    class            (nodeComponentDarkMatterProfile),                pointer     :: darkMatterProfileHost
    class            (massDistributionClass         )               , pointer     :: massDistributionHost_
    class            (kinematicsDistributionClass   )               , pointer     :: kinematicsHost_
    type             (coordinateSpherical           )                             :: coordinates
    type             (enumerationSolitonStatusType  )                             :: solitonStatus
    double precision                                 , dimension(:) , allocatable :: coefficientsCoreX      , coefficientsCoreY    , &
                     &                                                               coefficientsCoreZ      , coefficientsOuterX   , &
                     &                                                               coefficientsOuterY     , coefficientsOuterZ
    double precision                                                              :: timeMaximum            , densityCore          , &
                     &                                                               frequencyCore          , alphaCorePerComponent, &
                     &                                                               velocityDispersionJeans
    integer                                                                       :: i                      , countModes

    ! Initialize current satellites and secondary progenitors that can become satellites after a merger; skip primary or
    ! parentless central nodes.
    if (.not. node%isSatellite() .and. (node%isPrimaryProgenitor() .or. .not. associated(node%parent))) return
    ! Find the top-level host node.
    if (node%isSatellite()) then
       nodeHost => node%parent
    else
       nodeHost => node%parent%firstChild
    end if
    do while (associated(nodeHost%parent))
       nodeHost => nodeHost%parent
    end do
    ! Extract properties of the host node.
    basicHost   => nodeHost %basic()
    timeMaximum =  basicHost%time ()
    ! Reset to the immediate host.
    if (node%isSatellite()) then
       nodeHost => node%parent
    else
       nodeHost => node%parent%firstChild
    end if
    ! Get the host mass distribution. Doing so first ensures that the soliton status of the host has been determined.
    massDistributionHost_ => self%darkMatterProfileDMO_%get(nodeHost)
    darkMatterProfileHost => nodeHost%darkMatterProfile()
    solitonStatus         =  enumerationSolitonStatusType(darkMatterProfileHost%integerRank0MetaPropertyGet(self%solitonStatusID))
    if      (solitonStatus == solitonStatusSolitonNFW .or. solitonStatus == solitonStatusSolitonOnly) then
       ! Core oscillation frequency (eq. 5). The central density of the soliton is taken from the stored core density (which is
       ! the central density of the Schive et al. 2014 profile), the same quantity used to rescale the phase rate as the host
       ! evolves, so that the rescaling starts from exactly 1.
       densityCore   =darkMatterProfileHost%floatRank0MetaPropertyGet(self%densityCoreID) ! M☉/Mpc³
       frequencyCore =satelliteGranuleFrequencyCore(densityCore)                          ! Gyr⁻¹
    else if (solitonStatus == solitonStatusNfwOnly                                               ) then
       ! An NFW-only host has no soliton, so no core frequency exists (and the central density of the NFW profile is
       ! divergent). Instead use the outer granule frequency at the scale radius, which is close to the peak of the Jeans
       ! velocity dispersion of an NFW profile, and so to the highest outer granule frequency in the host. This frequency sets
       ! the number of Fourier modes, and is the reference for the (unscaled) phase rate of this host. The core term is zero
       ! for this host, so the frequency plays no role in its normalization.
       kinematicsHost_         => massDistributionHost_%kinematicsDistribution()
       coordinates             =  [darkMatterProfileHost%scale(),0.0d0,0.0d0]
       velocityDispersionJeans =  kinematicsHost_%velocityDispersion1D(coordinates,massDistributionHost_,massDistributionHost_) ! km/s
       frequencyCore           =  satelliteGranuleFrequencyOuter(self,velocityDispersionJeans)                                  ! Gyr⁻¹
       !![
       <objectDestructor name="kinematicsHost_"/>
       !!]
    else
       frequencyCore           =  0.0d0
       call Error_Report('soliton status of host halo is uninitialized'//{introspection:location})
    end if
    !![
    <objectDestructor name="massDistributionHost_"/>
    !!]
    ! Truncate the Paley-Wiener Fourier series at m = 4 f_core t_max (eq. 11), so that the fastest mode matches the frequency of
    ! the granule oscillations (eq. 10). The truncation reflects the natural frequency of the granules, above which no
    ! fluctuations are expected (footnote 2).
    countModes  =ceiling(countModesPerFrequency*frequencyCore*timeMaximum)
    ! Since m must be an integer, increase the integration time to match the integer number of modes (text following eq. 11).
    timeMaximum =countModes/(countModesPerFrequency*frequencyCore)
    ! Store properties of the Paley-Wiener series.
    basic => node%basic()
    call basic%floatRank0MetaPropertySet  (self%phaseID                 ,0.0d0        )
    call basic%floatRank0MetaPropertySet  (self%frequencyCoreReferenceID,frequencyCore)
    call basic%floatRank0MetaPropertySet  (self%timeMaximumID           ,timeMaximum  )
    call basic%integerRank0MetaPropertySet(self%countModesID            ,countModes   )
    ! Record the host, and its soliton status, for which this realization is drawn, so that a new realization can be drawn if
    ! either changes.
    call basic%integerRank0MetaPropertySet    (self%solitonStatusRealizationID,solitonStatus%ID                           )
    call basic%longIntegerRank0MetaPropertySet(self%identityHostRealizationID ,satelliteGranuleHaloIdentity(self,nodeHost))
    ! The core acceleration is isotropic and a_eff^core denotes its total three-dimensional RMS amplitude, so each Cartesian
    ! component carries a factor 1/√3 (eqs. 15 and 26).
    alphaCorePerComponent=self%alphaCore/sqrt(3.0d0)
    allocate(coefficientsCoreX (0:countModes))
    allocate(coefficientsCoreY (0:countModes))
    allocate(coefficientsCoreZ (0:countModes))
    allocate(coefficientsOuterX(0:countModes))
    allocate(coefficientsOuterY(0:countModes))
    allocate(coefficientsOuterZ(0:countModes))
    ! Draw independent dimensionless Gaussian Fourier coefficients for each Cartesian component of the core and outer stochastic
    ! fields, with widths α_core/√3 and α_outer in units of the respective effective accelerations (eqs. 15 and 26).
    do i=0,countModes
       coefficientsCoreX (i)=     alphaCorePerComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       coefficientsCoreY (i)=     alphaCorePerComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       coefficientsCoreZ (i)=     alphaCorePerComponent*node%hostTree%randomNumberGenerator_%standardNormalSample()
       coefficientsOuterX(i)=self%alphaOuter           *node%hostTree%randomNumberGenerator_%standardNormalSample()
       coefficientsOuterY(i)=self%alphaOuter           *node%hostTree%randomNumberGenerator_%standardNormalSample()
       coefficientsOuterZ(i)=self%alphaOuter           *node%hostTree%randomNumberGenerator_%standardNormalSample()
    end do
    ! Store the coefficients.
    call basic%floatRank1MetaPropertySet(self%coefficientsCoreXID ,coefficientsCoreX )
    call basic%floatRank1MetaPropertySet(self%coefficientsCoreYID ,coefficientsCoreY )
    call basic%floatRank1MetaPropertySet(self%coefficientsCoreZID ,coefficientsCoreZ )
    call basic%floatRank1MetaPropertySet(self%coefficientsOuterXID,coefficientsOuterX)
    call basic%floatRank1MetaPropertySet(self%coefficientsOuterYID,coefficientsOuterY)
    call basic%floatRank1MetaPropertySet(self%coefficientsOuterZID,coefficientsOuterZ)
    return
  end subroutine satelliteGranuleNodeInitialize

  function satelliteGranuleAcceleration(self,node) result(acceleration)
    !!{RST
    Compute the stochastic acceleration generated by fuzzy-dark-matter granules in the host halo. Core and outer stochastic fields
    are evaluated separately, and the outer contribution includes the velocity-dependent anisotropy.  Units: km/s/Gyr (same as
    other dynamical friction acceleration models).
    !!}
    use :: Galacticus_Nodes                   , only : nodeComponentBasic            , nodeComponentSatellite     , nodeComponentDarkMatterProfile, treeNode
    use :: Dark_Matter_Profiles_Soliton_Status, only : enumerationSolitonStatusType  , solitonStatusNfwOnly       , solitonStatusSolitonOnly
    use :: Coordinates                        , only : coordinateSpherical           , assignment(=)
    use :: Mass_Distributions                 , only : massDistributionClass         , kinematicsDistributionClass
    use :: Numerical_Constants_Astronomical   , only : gravitationalConstant_internal, MpcPerKmPerSToGyr
    use :: Vectors                            , only : Vector_Magnitude
    implicit none
    double precision                                , dimension(3)              :: acceleration
    class           (nodeOperatorSatelliteGranule  ), intent(inout), target     :: self
    type            (treeNode                      ), intent(inout)             :: node
    type            (treeNode                      )               , pointer    :: nodeHost
    class           (nodeComponentBasic            )               , pointer    :: basic
    class           (nodeComponentSatellite        )               , pointer    :: satellite
    class           (massDistributionClass         )               , pointer    :: massDistributionHost_
    class           (kinematicsDistributionClass   )               , pointer    :: kinematicsHost_
    class           (nodeComponentDarkMatterProfile)               , pointer    :: darkMatterProfileHost
    type            (coordinateSpherical           )                            :: coordinates                             , coordinatesSoliton
    type            (enumerationSolitonStatusType  )                            :: solitonStatus
    double precision                                                            :: velocityDispersionJeans                 , velocityDispersionJeansSoliton
    double precision                                                            :: densityLocal                            , densitySoliton                        , &
            &                                                                      massCore                                , radiusSoliton                         , &
            &                                                                      radiusCore
    double precision                                                            :: amplitudeCore                           , amplitudeOuter
    double precision                                                            :: frequencyCore                           , frequencyOuter
    double precision                                                            :: radius                                  , speed                                 , &
            &                                                                      phase                                   , timeMaximum
    double precision                                                            :: velocityDispersionGranule               , factorFiniteSize
    double precision                                                            :: factorTotal                             , factorPerpendicular                   , &
            &                                                                      factorParallel
    double precision                                , dimension(3)              :: positionSatellite                       , velocitySatellite
    double precision                                , dimension(:), allocatable :: basisFourier
    double precision                                , dimension(:), allocatable :: coefficientsCoreX                       , coefficientsCoreY                     , &
            &                                                                      coefficientsCoreZ                       , coefficientsOuterX                    , &
            &                                                                      coefficientsOuterY                      , coefficientsOuterZ
    double precision                                , dimension(3)              :: accelerationCoreUnscaled                , accelerationOuterUnscaled             , &
            &                                                                      accelerationOuterParallelUnscaled       , accelerationOuterPerpendicularUnscaled, &
            &                                                                      velocityDirection
    double precision                                , dimension(3)              :: accelerationOuterParallel               , accelerationOuterPerpendicular
    ! A floor on the radius, relative to the core radius, at which the density and Jeans velocity dispersion are evaluated. This
    ! is a numerical choice (not from Zhao, Benson & Du 2025) to avoid evaluating them at r=0.
    double precision                                               , parameter  :: fractionRadiusCoreMinimum        =1.0d-2
    integer                                                                     :: countModes
    !$GLC attributes initialized :: coefficientsCoreX, coefficientsCoreY, coefficientsCoreZ, coefficientsOuterX, coefficientsOuterY, coefficientsOuterZ

    ! Non-satellites experience no granule acceleration.
    if (.not.node%isSatellite()) then
      acceleration=[0.0d0,0.0d0,0.0d0]
      return
    end if
    ! Extract satellite and host properties.
    satellite             => node            %satellite        (                 )
    basic                 => node            %basic            (                 )
    positionSatellite     =  satellite       %position         (                 )
    radius                =  Vector_Magnitude                  (positionSatellite)
    velocitySatellite     =  satellite       %velocity         (                 )
    speed                 =  Vector_Magnitude                  (velocitySatellite)
    nodeHost              => node            %parent
    darkMatterProfileHost => nodeHost        %darkMatterProfile(                 )
    ! The granules belong to the host FDM halo, so both the density and the Jeans velocity dispersion must be evaluated from the
    ! host profile.
    massDistributionHost_ => self                 %darkMatterProfileDMO_%get                   (nodeHost)
    kinematicsHost_       => massDistributionHost_                      %kinematicsDistribution(        )
    ! Extract the Fourier coefficients for the accelerations.
    coefficientsCoreX =basic%floatRank1MetaPropertyGet(self%coefficientsCoreXID )
    coefficientsCoreY =basic%floatRank1MetaPropertyGet(self%coefficientsCoreYID )
    coefficientsCoreZ =basic%floatRank1MetaPropertyGet(self%coefficientsCoreZID )
    coefficientsOuterX=basic%floatRank1MetaPropertyGet(self%coefficientsOuterXID)
    coefficientsOuterY=basic%floatRank1MetaPropertyGet(self%coefficientsOuterYID)
    coefficientsOuterZ=basic%floatRank1MetaPropertyGet(self%coefficientsOuterZID)
    ! Extract other properties of the Fourier series.
    timeMaximum  =basic%floatRank0MetaPropertyGet  (self%timeMaximumID           )
    frequencyCore=basic%floatRank0MetaPropertyGet  (self%frequencyCoreReferenceID)
    phase        =basic%floatRank0MetaPropertyGet  (self%phaseID                 )
    countModes   =basic%integerRank0MetaPropertyGet(self%countModesID            )
    basisFourier =satelliteGranuleBasisFourier(phase,countModes)
    solitonStatus=enumerationSolitonStatusType(darkMatterProfileHost%integerRank0MetaPropertyGet(self%solitonStatusID))
    ! Compute acceleration amplitudes.
    if (solitonStatus == solitonStatusNfwOnly) then
        ! NFW-only: radiusCore and radiusSoliton are sentinel values (-1), so use only the density and Jeans velocity dispersion
        ! at the satellite.
        coordinates              = [radius,0.0d0,0.0d0]
        velocityDispersionJeans  =+kinematicsHost_      %velocityDispersion1D(coordinates,massDistributionHost_,massDistributionHost_) ! km/s
        densityLocal             =+massDistributionHost_%density             (coordinates                                            ) ! M☉/Mpc³
        amplitudeCore            = 0.0d0
        amplitudeOuter           = satelliteGranuleAmplitudeOuter(self,velocityDispersionJeans,densityLocal)
        frequencyOuter           = satelliteGranuleFrequencyOuter(self,velocityDispersionJeans             )
        velocityDispersionGranule= velocityDispersionJeans
    else if (solitonStatus == solitonStatusSolitonOnly) then
        ! Soliton-only: retain the core fluctuation and omit the outer granule term.
        massCore  =darkMatterProfileHost%floatRank0MetaPropertyGet(self%massCoreID  )
        radiusCore=darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusCoreID)
        if (radius <= radiusCore) then
           ! Core acceleration amplitude, a_eff^core = G M(r_c)/r_c² (eq. 4), applied only within the core radius.
           amplitudeCore=+gravitationalConstant_internal &
                &        *massCore                       &
                &        /radiusCore**2                  &
                &        /MpcPerKmPerSToGyr
        else
            amplitudeCore=+0.0d0
        end if
        amplitudeOuter   =+0.0d0
     else
        ! General (soliton+NFW) case.
        massCore     =darkMatterProfileHost%floatRank0MetaPropertyGet(self%massCoreID     )
        radiusCore   =darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusCoreID   )
        radiusSoliton=darkMatterProfileHost%floatRank0MetaPropertyGet(self%radiusSolitonID)
        ! Impose a small radial floor relative to the soliton core radius to avoid evaluating the density and Jeans velocity dispersion at r=0.
        radius            =max(radius,fractionRadiusCoreMinimum*radiusCore)
        coordinates       =[radius       ,0.0d0,0.0d0]
        coordinatesSoliton=[radiusSoliton,0.0d0,0.0d0]
        ! Compute the acceleration amplitudes. Inside the soliton, the outer contribution is fixed to its value at the soliton
        ! radius, r_sol (section 2.1, following eq. 3).
        velocityDispersionJeans        =+kinematicsHost_      %velocityDispersion1D(coordinates       ,massDistributionHost_,massDistributionHost_) ! km/s
        velocityDispersionJeansSoliton =+kinematicsHost_      %velocityDispersion1D(coordinatesSoliton,massDistributionHost_,massDistributionHost_) ! km/s
        densityLocal                   =+massDistributionHost_%density             (coordinates                                                   ) ! M☉/Mpc³
        densitySoliton                 =+massDistributionHost_%density             (coordinatesSoliton                                            ) ! M☉/Mpc³
        if (radius<=radiusCore) then
           ! Core acceleration amplitude, a_eff^core = G M(r_c)/r_c² (eq. 4), applied only within the core radius.
           amplitudeCore            =+gravitationalConstant_internal &                                                  ! km/s/Gyr
                &                    *massCore                       &
                &                    /radiusCore**2                  &
                &                    /MpcPerKmPerSToGyr
           amplitudeOuter           =satelliteGranuleAmplitudeOuter(self,velocityDispersionJeansSoliton,densitySoliton) ! km/s/Gyr
           frequencyOuter           =satelliteGranuleFrequencyOuter(self,velocityDispersionJeansSoliton               ) ! Gyr⁻¹
           velocityDispersionGranule=velocityDispersionJeansSoliton
        else if (radius<=radiusSoliton) then
           amplitudeCore            =0.0d0
           amplitudeOuter           =satelliteGranuleAmplitudeOuter(self,velocityDispersionJeansSoliton,densitySoliton)
           frequencyOuter           =satelliteGranuleFrequencyOuter(self,velocityDispersionJeansSoliton               )
           velocityDispersionGranule=velocityDispersionJeansSoliton
        else
           amplitudeCore            =0.0d0
           amplitudeOuter           =satelliteGranuleAmplitudeOuter(self,velocityDispersionJeans       ,densityLocal  )
           frequencyOuter           =satelliteGranuleFrequencyOuter(self,velocityDispersionJeans                      )
           velocityDispersionGranule=velocityDispersionJeans
        end if
    end if
    ! Keep the tested point-mass path unchanged. For a finite-size satellite, multiply only the outer stochastic amplitude by the
    ! relative suppression inferred from the finite-size calibration. The Fourier process and its correlation frequency are
    ! unchanged.
    if (self%applyFiniteSize .and. solitonStatus /= solitonStatusSolitonOnly) then
        factorFiniteSize=satelliteGranuleFactorFiniteSize(self,node,velocityDispersionGranule)
        amplitudeOuter  =factorFiniteSize*amplitudeOuter
    end if
    !![
    <objectDestructor name="kinematicsHost_"      />
    <objectDestructor name="massDistributionHost_"/>
    !!]

    ! Evaluate the Fourier series (eq. 16). The Fourier coefficients and basis are dimensionless. Since frequency is in Gyr⁻¹ and
    ! timeMaximum is in Gyr, √(frequency*timeMaximum) is also dimensionless. Therefore the unscaled accelerations are
    ! dimensionless.
    if (solitonStatus == solitonStatusNfwOnly) then
        ! An NFW-only halo has no core fluctuation.
        accelerationCoreUnscaled=[0.0d0,0.0d0,0.0d0]
    else
        accelerationCoreUnscaled=+[                                             &
             &                     dot_product(coefficientsCoreX,basisFourier), &
             &                     dot_product(coefficientsCoreY,basisFourier), &
             &                     dot_product(coefficientsCoreZ,basisFourier)  &
             &                    ]                                             &
             &                   /sqrt(frequencyCore*timeMaximum)
    end if
    ! For a soliton-only profile the acceleration is due to the core only. Scale the unscaled acceleration by the amplitude and
    ! return it.
    if (solitonStatus == solitonStatusSolitonOnly) then
        acceleration=amplitudeCore*accelerationCoreUnscaled
        return
    end if
    ! For profiles with an NFW component include the acceleration from the granules in the outer halo.
    accelerationOuterUnscaled=+[                                              &
         &                      dot_product(coefficientsOuterX,basisFourier), &
         &                      dot_product(coefficientsOuterY,basisFourier), &
         &                      dot_product(coefficientsOuterZ,basisFourier)  &
         &                     ]                                              &
         &                    /sqrt(frequencyOuter*timeMaximum)
    ! Compute a unit vector in the direction of the satellite velocity.
    if (speed > 0.0d0) then
       velocityDirection=+velocitySatellite &
            &            /speed
    else
        velocityDirection=[0.0d0,0.0d0,0.0d0]
    end if
    ! Rescaling factors for the velocity-dependent anisotropy, A_total and A_⊥ (eq. B28) and A_∥ (eq. B29). speed and
    ! velocityDispersionJeans are both in km/s, so these factors are dimensionless.
    factorTotal        =sqrt(1.0d0+      (speed/velocityDispersionJeans)**2)
    factorPerpendicular=sqrt(1.0d0+0.5d0*(speed/velocityDispersionJeans)**2)
    factorParallel     =1.0d0/(3.0d0/factorTotal-2.0d0/factorPerpendicular)
    ! Divide the components of the outer acceleration parallel and perpendicular to the satellite velocity by √A_∥ and √A_⊥
    ! respectively (eq. 17). This velocity-dependent rescaling is applied only to the outer acceleration, not to the core
    ! acceleration (which is set to zero at r > r_c).
    accelerationOuterParallelUnscaled     =dot_product(accelerationOuterUnscaled,velocityDirection)*velocityDirection
    accelerationOuterPerpendicularUnscaled=accelerationOuterUnscaled-accelerationOuterParallelUnscaled
    accelerationOuterParallel             =accelerationOuterParallelUnscaled     /sqrt(factorParallel     )
    accelerationOuterPerpendicular        =accelerationOuterPerpendicularUnscaled/sqrt(factorPerpendicular)
    ! amplitudeCore and amplitudeOuter are in km/s/Gyr, while all stochastic and anisotropy factors are dimensionless. The
    ! returned acceleration is therefore in km/s/Gyr, as required by satellite%velocityRate().
    acceleration=+amplitudeCore *  accelerationCoreUnscaled          &
         &       +amplitudeOuter*(                                   &
         &                        +accelerationOuterParallel         &
         &                        +accelerationOuterPerpendicular    &
         &                       )
    return
  end function satelliteGranuleAcceleration

  function satelliteGranuleBasisFourier(phase,countModes) result(basisFourier)
    !!{RST
    Return the dimensionless Fourier basis of eq. (16) of :cite:`zhao_granule_2025`. Both ``phase`` (:math:`\tau`) and
    ``basisFourier`` are dimensionless; ``countModes`` is the number of non-zero Fourier modes, :math:`m`. The first element is
    :math:`1/\sqrt{2}`, followed by :math:`\cos(n\tau/2)` for :math:`n = 1, 2, \ldots, m`.
    !!}
    implicit none
    integer         , intent(in)                :: countModes
    double precision, intent(in)                :: phase
    double precision, allocatable, dimension(:) :: basisFourier
    integer                                     :: n

    allocate(basisFourier(0:countModes))
    basisFourier(0)=1.0d0/sqrt(2.0d0)
    do n=1,countModes
        basisFourier(n)=cos(dble(n)*phase/2.0d0)
    end do
    return
  end function satelliteGranuleBasisFourier

  double precision function satelliteGranuleFrequencyCore(densityCore)
    !!{RST
    Return the oscillation frequency (in Gyr\ :math:`^{-1}`) of a soliton core with central density ``densityCore`` (in
    :math:`M_\odot\,\mathrm{Mpc}^{-3}`), using eq. (5) of :cite:`zhao_granule_2025`.
    !!}
    implicit none
    double precision, intent(in   ) :: densityCore

    satelliteGranuleFrequencyCore=+frequencySolitonNormalization &
         &                        *sqrt(                         &
         &                              +densityCore             &
         &                              /densitySolitonReference &
         &                             )
    return
  end function satelliteGranuleFrequencyCore

  double precision function satelliteGranuleWavelengthDeBroglie(self,velocityDispersionJeans)
    !!{RST
    Return the de Broglie wavelength (in Mpc), :math:`\lambda_\mathrm{dB} = h/(m_\mathrm{b} \sigma_\mathrm{Jeans})`, for a
    host with Jeans velocity dispersion ``velocityDispersionJeans`` (in km/s), using eq. (2) of :cite:`zhao_granule_2025`.
    !!}
    use :: Numerical_Constants_Astronomical, only : megaParsec
    use :: Numerical_Constants_Prefixes    , only : kilo
    use :: Numerical_Constants_Physical    , only : plancksConstant
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout) :: self
    double precision                              , intent(in   ) :: velocityDispersionJeans

    ! plancksConstant [J s] / (massParticleSI [kg] * velocity [m/s]) gives the wavelength in meters; division by megaParsec
    ! converts it to Mpc.
    satelliteGranuleWavelengthDeBroglie=+plancksConstant                &
         &                              /self%massParticleSI            &
         &                              /(velocityDispersionJeans*kilo) &
         &                              /megaParsec
    return
  end function satelliteGranuleWavelengthDeBroglie

  double precision function satelliteGranuleAmplitudeOuter(self,velocityDispersionJeans,densityHost)
    !!{RST
    Compute the outer-halo effective granule acceleration amplitude (in km/s/Gyr), :math:`a_\mathrm{eff}^\mathrm{outskirt} = G
    m_\mathrm{eff}/d_\mathrm{eff}^2`, using eqs. (1)--(3) of :cite:`zhao_granule_2025`.
    !!}
    use :: Numerical_Constants_Astronomical, only : gravitationalConstant_internal, MpcPerKmPerSToGyr
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout), target :: self
    double precision                              , intent(in   )         :: velocityDispersionJeans, densityHost
    double precision                                                      :: wavelengthDeBroglie    , diameterGranule, &
            &                                                                massGranule

    wavelengthDeBroglie=satelliteGranuleWavelengthDeBroglie(self,velocityDispersionJeans)     ! Mpc (eq. 2)
    diameterGranule    =ratioDiameterWavelength*wavelengthDeBroglie                           ! Mpc (text preceding eq. 3)
    massGranule        =densityHost*(fractionWavelengthMass*wavelengthDeBroglie)**3           ! M☉  (eq. 1)
    ! gravitationalConstant_internal*massGranule/diameterGranule² has units (km/s)²/Mpc (eq. 3). Convert to the velocity
    ! evolution unit km/s/Gyr.
    satelliteGranuleAmplitudeOuter=+gravitationalConstant_internal & ! km/s/Gyr
         &                         *massGranule                    &
         &                         /diameterGranule**2             &
         &                         /MpcPerKmPerSToGyr
    return
  end function satelliteGranuleAmplitudeOuter

  double precision function satelliteGranuleFrequencyOuter(self,velocityDispersionJeans)
    !!{RST
    Return the characteristic frequency (in Gyr\ :math:`^{-1}`) of outer-halo granule fluctuations, :math:`f = m
    \sigma_\mathrm{Jeans}^2/(0.35\sqrt{2}h)`, for a host with Jeans velocity dispersion ``velocityDispersionJeans`` (in km/s),
    using eq. (6) of :cite:`zhao_granule_2025`. This follows from :math:`f \sim \sigma_\mathrm{h}/d_\mathrm{eff}`, where the
    velocity dispersion of the granules is :math:`\sigma_\mathrm{h} \approx \sigma_\mathrm{Jeans}/\sqrt{2}` and their effective
    diameter is :math:`d_\mathrm{eff} \approx 0.35 \lambda_\mathrm{dB}`.
    !!}
    use :: Numerical_Constants_Astronomical, only : gigaYear
    use :: Numerical_Constants_Prefixes    , only : kilo
    use :: Numerical_Constants_Physical    , only : plancksConstant
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout) :: self
    double precision                              , intent(in   ) :: velocityDispersionJeans

    satelliteGranuleFrequencyOuter=+self%massParticleSI               &
         &                         *(velocityDispersionJeans*kilo)**2 &
         &                         /ratioDiameterWavelength           &
         &                         /sqrt(2.0d0)                       &
         &                         /plancksConstant                   &
         &                         *gigaYear
    return
  end function satelliteGranuleFrequencyOuter

  double precision function satelliteGranuleFactorFiniteSize(self,node,velocityDispersionJeans)
    !!{RST
    Return the finite-size suppression of the outer granule acceleration.  The satellite half-mass radius is evaluated from its
    current bound dark matter mass. The effective granule size is :math:`d_\mathrm{eff}=0.35\lambda_\mathrm{dB}`. Satellites with
    :math:`r_\mathrm{half}/d_\mathrm{eff}\leq0.40` retain the point-mass amplitude. Above this transition, the acceleration
    amplitude is suppressed as :math:`(r_\mathrm{half}/0.40d_\mathrm{eff})^{-0.229}`. Because a velocity-diffusion coefficient is
    proportional to acceleration variance, the corresponding diffusion coefficient is multiplied by the square of this factor.
    !!}
    use :: Galacticus_Nodes          , only : nodeComponentSatellite, treeNode
    use :: Galactic_Structure_Options, only : componentTypeAll      , massTypeDark, radiusLarge
    use :: Mass_Distributions        , only : massDistributionClass
    implicit none
    class           (nodeOperatorSatelliteGranule), intent(inout), target   :: self
    type            (treeNode                    ), intent(inout), target   :: node
    double precision                              , intent(in   )           :: velocityDispersionJeans
    class           (nodeComponentSatellite      )               , pointer  :: satellite
    class           (massDistributionClass       )               , pointer  :: massDistributionSatellite_
    double precision                                                        :: diameterGranule                 , massBound            , &
            &                                                                  massMaximum                     , massHalf             , &
            &                                                                  massAtOrigin                    , radiusHalf           , &
            &                                                                  ratioSize
    ! The transition in r_half/d_eff above which finite-size suppression occurs, and the exponent, B, of the power-law fit, α = A
    ! (r_half/d_eff)^B, to the suppression above that transition (section 4.2, eq. 33, and Fig. 6).
    double precision                                            , parameter :: ratioSizeTransition       =0.40d0, exponentSize=-0.229d0

    ! Extract the satellite mass distribution.
    satellite                 => node% satellite      (                                                    )
    massDistributionSatellite_=> node%massDistribution(componentType=componentTypeAll,massType=massTypeDark)
    ! Limit the requested bound mass to the finite mass represented by the satellite profile, then locate the radius containing
    ! half of that mass.
    massMaximum =massDistributionSatellite_%massEnclosedBySphere(radius=radiusLarge)
    massBound   =max(0.0d0,min(satellite%boundMass(),massMaximum))
    massHalf    =0.5d0*massBound
    massAtOrigin=massDistributionSatellite_%massEnclosedBySphere(radius=0.0d0)
    if (massHalf > massAtOrigin) then
       radiusHalf=massDistributionSatellite_%radiusEnclosingMass(mass=massHalf)
    else
       radiusHalf=0.0d0
    end if
    !![
    <objectDestructor name="massDistributionSatellite_"/>
    !!]
    ! Compute the ratio of the satellite size to that of granules.
    diameterGranule=ratioDiameterWavelength*satelliteGranuleWavelengthDeBroglie(self,velocityDispersionJeans) ! Mpc
    ratioSize      =radiusHalf/diameterGranule
    ! Compute the finite size amplitude factor. This is the ratio α(r_half/d_eff)/α(0.40) of eq. (33), so the normalization A =
    ! 7.755 of that fit cancels, and the factor is 1 at the transition. (Evaluated at the transition, the fit gives α ≈ 9.6, close to
    ! the value α ≈ 9.3 found for point-mass-like satellites with 0.26 ≲ r_half/d_eff ≲ 0.39.)
    if (ratioSize <= ratioSizeTransition) then
       satelliteGranuleFactorFiniteSize=1.0d0
    else
       satelliteGranuleFactorFiniteSize=(                     &
            &                            +ratioSize           &
            &                            /ratioSizeTransition &
            &                           )**exponentSize
    end if
    return
  end function satelliteGranuleFactorFiniteSize
