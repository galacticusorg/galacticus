  subroutine satelliteGranuleDifferentialEvolutionScales(self,node)
    !!{RST
    Set the absolute ODE solver scale for the dimensionless granule phase.
    !!}
    use :: Galacticus_Nodes, only : nodeComponentBasic, treeNode
    implicit none
    class(nodeOperatorSatelliteGranule), intent(inout)          :: self
    type (treeNode                    ), intent(inout)          :: node
    class(nodeComponentBasic          )               , pointer :: basic

    ! Non-satellites are not affected by granules.
    if (.not.node%isSatellite()) return
    ! Set an absolute scale of 1 for the phase - this is a dimensionless time, measured in cycles of the fluctuations.
    basic => node%basic()
    call basic%floatRank0MetaPropertyScale(self%phaseID,1.0d0)
    return
  end subroutine satelliteGranuleDifferentialEvolutionScales

  subroutine satelliteGranuleDifferentialEvolution(self,node,interrupt,functionInterrupt,propertyType)
    !!{RST
    Compute accelerations due to granules.
    !!}
    use :: Galacticus_Nodes                    , only : nodeComponentBasic          , nodeComponentSatellite, nodeComponentDarkMatterProfile, treeNode
    use :: Dark_Matter_Profiles_Soliton_Status , only : enumerationSolitonStatusType
    implicit none
    class     (nodeOperatorSatelliteGranule  ), intent(inout), target  :: self
    type      (treeNode                      ), intent(inout), target  :: node
    type      (treeNode                      ), pointer                :: nodeHost
    logical                                   , intent(inout)          :: interrupt
    procedure (interruptTask                 ), intent(inout), pointer :: functionInterrupt
    class     (nodeComponentBasic            ), pointer                :: basic
    class     (nodeComponentSatellite        ), pointer                :: satellite
    class     (nodeComponentDarkMatterProfile), pointer                :: darkMatterProfileHost
    integer                                   , intent(in   )          :: propertyType
    type      (enumerationSolitonStatusType)                           :: solitonStatus
    double precision                          , dimension(3)           :: acceleration
    !$GLC attributes unused :: propertyType

    ! Non-satellites experience no acceleration from granules.
    if (.not.node%isSatellite()) return
    ! Extract the required components.
    satellite             => node%satellite()
    basic                 => node%basic    ()
    nodeHost              => node%parent
    ! Evaluate the acceleration first. This gets the host mass distribution, which ensures that the soliton status of the host
    ! is current before it is read below.
    acceleration          =  self%acceleration(node)
    darkMatterProfileHost => nodeHost%darkMatterProfile()
    solitonStatus         =  enumerationSolitonStatusType(darkMatterProfileHost%integerRank0MetaPropertyGet(self%solitonStatusID))
    ! The realization was drawn for a specific host in a specific soliton status. If the satellite has moved to a different host
    ! (e.g. because its host merged, or because of sub-subhalo promotion), or the host has changed status (e.g. to soliton-only
    ! after tidal stripping, or to NFW-only if no soliton solution exists), the realization (its seed and, for NFW-only hosts,
    ! its reference frequency) no longer describes the host. Trigger an interrupt to draw a new realization for the current host.
    if     (                                                                                                                       &
         &   solitonStatus%ID                            /= basic%integerRank0MetaPropertyGet    (self%solitonStatusRealizationID) &
         &  .or.                                                                                                                   &
         &   satelliteGranuleHaloIdentity(self,nodeHost) /= basic%longIntegerRank0MetaPropertyGet(self%identityHostRealizationID ) &
         & ) then
       interrupt         =  .true.
       functionInterrupt => satelliteGranuleRealizationRedraw
       self_             => self
       return
    end if
    ! The phase counts cycles of the fluctuations, so advances at the current core frequency (or, for an NFW-only host, at the
    ! reference frequency fixed when the realization was drawn).
    call basic    %floatRank0MetaPropertyRate(self%phaseID,satelliteGranuleFrequencyPhase(self,basic,darkMatterProfileHost,solitonStatus))
    call satellite%velocityRate              (             acceleration                                                                  )
    return
  end subroutine satelliteGranuleDifferentialEvolution

  double precision function satelliteGranuleFrequencyPhase(self,basic,darkMatterProfileHost,solitonStatus)
    !!{RST
    Return the rate (in Gyr\ :math:`^{-1}`) at which the granule phase, which counts cycles of the fluctuations, advances. For a
    host with a soliton this is the core oscillation frequency (eq. 5 of :cite:`zhao_granule_2025`) for the current core density
    of the host. An NFW-only host has no core frequency, so the reference frequency stored when the realization was drawn is used.
    !!}
    use :: Galacticus_Nodes                   , only : nodeComponentBasic          , nodeComponentDarkMatterProfile
    use :: Dark_Matter_Profiles_Soliton_Status, only : enumerationSolitonStatusType, solitonStatusNfwOnly
    implicit none
    class(nodeOperatorSatelliteGranule  ), intent(inout) :: self
    class(nodeComponentBasic            ), intent(inout) :: basic
    class(nodeComponentDarkMatterProfile), intent(inout) :: darkMatterProfileHost
    type (enumerationSolitonStatusType  ), intent(in   ) :: solitonStatus

    if (solitonStatus == solitonStatusNfwOnly) then
       satelliteGranuleFrequencyPhase=basic%floatRank0MetaPropertyGet(self%frequencyReferenceID)
    else
       satelliteGranuleFrequencyPhase=satelliteGranuleFrequencyCore(darkMatterProfileHost%floatRank0MetaPropertyGet(self%densityCoreID))
    end if
    return
  end function satelliteGranuleFrequencyPhase

