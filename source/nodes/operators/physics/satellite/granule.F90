  !![
  <nodeOperator name="nodeOperatorSatelliteGranule" docformat="rst">
   <description>
   A node operator class that applies the stochastic gravitational acceleration generated by fuzzy-dark-matter granules to an
   orbiting satellite, following the model of :cite:`zhao_granule_2025`.

   The stochastic acceleration is represented by two statistically independent truncated Paley--Wiener Fourier series: one
   describing fluctuations of the solitonic core and one describing granules in the outer halo. For each Cartesian component,
   the acceleration is written as

   .. math::

      a_i(\tau) =
      \frac{a_\mathrm{eff}}{\sqrt{f_\mathrm{granule}t_\mathrm{max}}}
      \left[
      \frac{A_{i,0}}{\sqrt{2}}+
      \sum_{n=1}^{m}A_{i,n}\cos(n\tau/2)
      \right],

   where the :math:`A_{i,n}` are independent Gaussian random variables, :math:`f_\mathrm{granule}` is the characteristic
   fluctuation frequency, and the series is truncated at

   .. math::

      m = 4 f_\mathrm{core}t_\mathrm{max}.

   The Fourier coefficients, truncation order, and maximum time are fixed when a realization is drawn, which happens when the
   satellite state is initialized. The core oscillation frequency is

   .. math::

      f_\mathrm{core}
      =
      10.94\,\mathrm{Gyr}^{-1}
      \left(
      \frac{\rho_\mathrm{core}}
           {10^9\,M_\odot\,\mathrm{kpc}^{-3}}
      \right)^{1/2}.

   As the host halo evolves, the stored Fourier realization is retained, while its phase rate is rescaled by the ratio of the
   current core frequency to its value when the realization was drawn. Thus, changes in the host core density alter the
   fluctuation timescale without redrawing the stochastic field or changing the number of Fourier modes. A new realization is
   drawn, with the phase reset to zero, if the satellite moves to a different host halo (for example because its host merges,
   or through sub-subhalo promotion), or if its host changes soliton status (for example to soliton-only after tidal
   stripping). In either case the frequencies that set the phase rate and the number of modes change discontinuously, so the
   fluctuations are not correlated across the change. Promotion of the host to its descendant in the merger tree does not
   change the host halo, so does not cause a new realization to be drawn.

   Within the solitonic core, the effective three-dimensional core acceleration is

   .. math::

      a_\mathrm{eff}^\mathrm{core}
      =
      \frac{G M_\mathrm{core}}{r_\mathrm{core}^2},

   and is applied only for :math:`r\leq r_\mathrm{core}`. Its Cartesian coefficients have standard deviation
   :math:`[\alpha_\mathrm{core}]/\sqrt{3}`, since :math:`a_\mathrm{eff}^\mathrm{core}` denotes the total isotropic RMS amplitude.

   The outer-halo contribution is estimated by treating granules as effective quasiparticles, with

   .. math::

      a_\mathrm{eff}^\mathrm{outer}
      =
      \frac{Gm_\mathrm{eff}}{d_\mathrm{eff}^2}.

   Its amplitude and frequency are evaluated using the density and Jeans velocity dispersion of the host halo. Inside the
   soliton they are fixed to their values at the soliton boundary; outside the soliton they are evaluated at the satellite
   position. The components parallel and perpendicular to the satellite velocity are rescaled separately to account for the
   velocity-dependent anisotropy of the granule perturbations. This rescaling is applied only to the outer contribution.

   For a soliton--NFW host, both the core and outer contributions are included. For a soliton-only host, only the core
   contribution is retained. For an NFW-only host, only the outer contribution is used, so the divergent central density of the
   NFW profile is never evaluated. Such a host has no core frequency, so the truncation order is instead set by replacing
   :math:`f_\mathrm{core}` with the outer granule frequency evaluated at the scale radius of the host, close to the peak of its
   Jeans velocity dispersion.

   If ``[applyFiniteSize]`` is false, the satellite is treated as a point mass. If it is true, the outer stochastic amplitude is
   suppressed according to the satellite half-mass radius relative to the effective granule size, following the finite-size
   calibration of :cite:`zhao_granule_2025`. The core contribution and fluctuation frequencies are unchanged by this
   correction.

   This operator requires a fuzzy-dark-matter particle model, a host dark-matter profile providing the soliton properties and
   Jeans velocity dispersion, and a satellite component which evolves the satellite position and velocity, such as the
   ``orbiting`` component.
   </description>
  </nodeOperator>
  !!]
