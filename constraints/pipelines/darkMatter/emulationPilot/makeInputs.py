#!/usr/bin/env python3
"""Build the inputs of an emulator campaign for the progenitor mass function stage of the dark-matter pipeline.

From the files generated by `progenitorMassFunctionGenerateContent.py` (in the pipeline's output directory), write:

* `emulatorBase.xml`, in the pipeline's output directory (alongside the stage's own base file, whose includes it
  shares): the stage's model, run standalone, with a random number generator (whose seed each run replaces) and,
  optionally, a different number of trees per decade; and
* `design.xml`, in the campaign directory: an `emulatorDesign` task over the stage's active parameters, except
  `rootVarianceTargetFractional`, which changes only the likelihood (it is a parameter of the emulated likelihood, not an
  emulator input).

Andrew Benson, Claude (13-October-2026)
"""
import argparse
import copy
import os

import lxml.etree as ET

parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
parser.add_argument('--pipelineOutput', required=True, help="the pipeline's output directory, holding the generated stage")
parser.add_argument('--campaignDirectory', required=True, help='the directory for the design, change files, and model outputs')
parser.add_argument('--treesPerDecade', type=int, default=None, help='trees per decade (default: as generated)')
parser.add_argument('--countSamples', type=int, default=512, help='the number of design points (a power of two)')
parser.add_argument('--seed', type=int, default=42, help='the seed of the design (its random shift)')
args = parser.parse_args()
pipeline = os.path.abspath(args.pipelineOutput) + '/'
campaign = os.path.abspath(args.campaignDirectory) + '/'
os.makedirs(campaign, exist_ok=True)

bases = [name for name in os.listdir(pipeline) if name.startswith('progenitorMassFunctionBase_') and name.endswith('.xml')]
if len(bases) != 1:
    raise RuntimeError(f'expected one progenitor mass function base file in {pipeline}, found {len(bases)}: select one simulation')
base = ET.parse(pipeline + bases[0])
root = base.getroot()
if args.treesPerDecade is not None:
    root.find('mergerTreeBuildMasses/treesPerDecade').set('value', str(args.treesPerDecade))
# Make any relative include absolute, so that the base file does not depend on its location.
for include in root.iter('{http://www.w3.org/2001/XInclude}include'):
    if not include.get('href').startswith('/'):
        include.set('href', pipeline + include.get('href'))
if root.find('randomNumberGenerator') is None:
    rng = ET.SubElement(root, 'randomNumberGenerator', value='GSL')
    ET.SubElement(rng, 'seed', value='9372')
base.write(pipeline + 'emulatorBase.xml', xml_declaration=True, encoding='UTF-8')

config = ET.parse(pipeline + 'progenitorMassFunctionConfig.xml').getroot()
design = ET.Element('parameters')
ET.SubElement(design, 'formatVersion').text = '2'
task = ET.SubElement(design, 'task', value='emulatorDesign')
ET.SubElement(task, 'designFileName', value=campaign + 'design.hdf5')
ET.SubElement(task, 'changeFilesRoot', value=campaign + 'changes/point')
ET.SubElement(task, 'outputFileNameRoot', value=campaign + 'models/point')
ET.SubElement(task, 'seedPerPoint', value='true')
names = []
for parameter in config.find('posteriorSampleSimulation').findall('modelParameter'):
    name = parameter.find('name').get('value')
    if name.endswith('rootVarianceTargetFractional'):
        continue
    task.append(copy.deepcopy(parameter))
    names.append(name)
samples = ET.SubElement(task, 'posteriorSamples', value='sobol')
ET.SubElement(samples, 'countSamples', value=str(args.countSamples))
rng = ET.SubElement(design, 'randomNumberGenerator', value='GSL')
ET.SubElement(rng, 'seed', value=str(args.seed))
ET.ElementTree(design).write(campaign + 'design.xml', pretty_print=True, xml_declaration=True, encoding='UTF-8')
os.makedirs(campaign + 'changes', exist_ok=True)
os.makedirs(campaign + 'models', exist_ok=True)
print(f"wrote {pipeline}emulatorBase.xml ({bases[0]}), and {campaign}design.xml over {len(names)} parameters:")
for name in names:
    print(f'  {name}')
